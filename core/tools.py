import os
import subprocess
import tempfile
import shutil
from github import Github, GithubException
from git import Repo
import re

g = Github(os.getenv("GITHUB_TOKEN"))

def get_issue_details(repo_url: str, issue_number: int):
    """Fetch issue body and repo name from URL"""
    # Extract repo name from URL: https://github.com/owner/repo
    match = re.search(r"github\.com/([^/]+/[^/]+)", repo_url)
    if not match:
        raise ValueError("Invalid GitHub URL")
    repo_full_name = match.group(1)
    
    repo = g.get_repo(repo_full_name)
    issue = repo.get_issue(issue_number)
    
    return {
        "body": issue.body or "No description provided.",
        "repo_full_name": repo_full_name,
        "repo": repo
    }

def get_repo_structure(repo_full_name: str):
    """Fetch top-level file/folder structure using GitHub API"""
    repo = g.get_repo(repo_full_name)
    contents = repo.get_contents("")
    structure = []
    for content in contents:
        structure.append(content.path)
    return "\n".join(structure[:30])  # Limit to 30 items to save tokens

def clone_repo(repo_url: str, target_dir: str):
    """Clone the repository to a temp directory"""
    if os.path.exists(target_dir):
        shutil.rmtree(target_dir)
    Repo.clone_from(repo_url, target_dir)
    return target_dir

def apply_diff_and_run_tests(repo_path: str, diff_text: str, test_command: str = "pytest"):
    """Apply the diff to the repo and run tests"""
    try:
        # Write diff to a patch file and apply it
        patch_path = os.path.join(repo_path, "changes.patch")
        with open(patch_path, "w", encoding="utf-8") as f:
            f.write(diff_text)
        
        # Apply patch using git apply
        result = subprocess.run(
            ["git", "apply", "--whitespace=fix", patch_path],
            cwd=repo_path,
            capture_output=True,
            text=True
        )
        
        if result.returncode != 0:
            return {"success": False, "output": result.stderr, "error": "Patch application failed"}
        
        # Run tests
        test_result = subprocess.run(
            test_command.split(),
            cwd=repo_path,
            capture_output=True,
            text=True,
            timeout=30
        )
        
        return {
            "success": test_result.returncode == 0,
            "output": test_result.stdout + "\n" + test_result.stderr,
            "exit_code": test_result.returncode
        }
        
    except subprocess.TimeoutExpired:
        return {"success": False, "output": "Tests timed out after 30 seconds"}
    except Exception as e:
        return {"success": False, "output": str(e)}

def create_pull_request(repo_url: str, issue_number: int, diff_text: str, repo_path: str):
    """Commit changes, push, and create PR"""
    match = re.search(r"github\.com/([^/]+/[^/]+)", repo_url)
    repo_full_name = match.group(1)
    repo = g.get_repo(repo_full_name)
    
    # Create a new branch
    branch_name = f"fix-issue-{issue_number}-auto"
    source_branch = repo.get_branch(repo.default_branch)
    try:
        # Try to create ref
        repo.create_git_ref(ref=f"refs/heads/{branch_name}", sha=source_branch.commit.sha)
    except GithubException:
        pass  # Branch might already exist
    
    # Add, commit, push via GitPython
    repo_git = Repo(repo_path)
    repo_git.git.add(".")
    repo_git.git.commit("-m", f"🤖 AI fix for issue #{issue_number}")
    repo_git.git.push("origin", branch_name)
    
    # Create PR
    pr = repo.create_pull(
        title=f"🤖 AI-generated fix for #{issue_number}",
        body=f"This PR was automatically generated by SWE-Agent Lite to fix issue #{issue_number}.\n\nTests passed successfully.",
        head=branch_name,
        base=repo.default_branch
    )
    
    return pr.html_url